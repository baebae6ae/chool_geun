import { createRequire } from 'module';
const { chromium } = createRequire(import.meta.url)('playwright');
const out = process.argv[2];
const b = await chromium.launch();
const p = await b.newPage({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 2 });
p.on('pageerror', (e) => console.log('ERR', e.message));
await p.goto('http://localhost:5179/chool_geun/?gallery&diary'); await p.waitForTimeout(2500);
await p.click('[aria-label="괜찮"]'); await p.click('.diary-memo-btn');
await p.fill('.diary-memo', '팀장님이 커피 사 줌. 오늘은 봐준다'); await p.waitForTimeout(400);
await p.screenshot({ path: `${out}/diary.png` });
await b.close();
