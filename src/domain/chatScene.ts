export interface ChatLine {
  /** 내가 보낸 말풍선이면 true */
  me: boolean;
  text: string;
}

export interface ChatScene {
  /** 대화방 이름 (상대) */
  who: string;
  /** 대화: 마지막 줄은 늘 상대의 어이없는 말 */
  lines: ChatLine[];
  /** 사이다 답변 */
  retort: string;
}

/** '>'로 시작하는 줄은 내가 보낸 말, 아니면 상대의 말 */
const sc = (who: string, lines: string[], retort: string): ChatScene => ({
  who,
  lines: lines.map((t) => (t.startsWith('>') ? { me: true, text: t.slice(1) } : { me: false, text: t })),
  retort,
});

